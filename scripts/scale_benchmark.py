"""Scale benchmark: entity resolution time and MCP lookup latency as the data grows.

    uv run python scripts/scale_benchmark.py 10 40 100 > docs/reports/scale_report.md

Each argument k builds a dataset from k generator seeds (record ids prefixed per seed, so
records never collide). The same 25 company names recur in every seed, so this measures
speed, not accuracy: many look-alike customers make blocking and lookups *harder* than a
real export of the same size.
"""

from __future__ import annotations

import sys
import tempfile
import time
from datetime import date
from pathlib import Path

from canon.ingest import load_all
from canon.mcp_server import CallerDirectory, CanonService, ServiceConfig
from canon.resolve.pipeline import ResolverConfig, resolve
from canon.score import FactScoringConfig
from canon.synth import generate

AS_OF = date(2026, 10, 1)
IDENTITIES = Path(__file__).resolve().parents[1] / "data" / "synthetic" / "identities.json"
QUERIES = ["Atlas Logistique", "zitoun cosmetics", "أطلس لوجيستيك", "no such company xyz"]


def build(k: int):
    records = []
    for seed in range(1, k + 1):
        with tempfile.TemporaryDirectory() as d:
            generate(Path(d), seed=seed)
            for r in load_all(Path(d)):
                rid = f"s{seed}:{r.record_id}"
                facts = [f.model_copy(update={"record_id": rid}) for f in r.facts]
                records.append(r.model_copy(update={"record_id": rid, "facts": facts}))
    return records


def main() -> None:
    rows = []
    for k in [int(a) for a in sys.argv[1:]] or [10, 40]:
        records = build(k)
        t = time.perf_counter()
        res = resolve(records, ResolverConfig(facts=FactScoringConfig(as_of=AS_OF)))
        resolve_s = time.perf_counter() - t
        service = CanonService(
            records,
            {g.entity_id: g.members for g in res.golden},
            CallerDirectory.from_file(IDENTITIES),
            ServiceConfig(facts=FactScoringConfig(as_of=AS_OF)),
        )
        t = time.perf_counter()
        for q in QUERIES:
            service.get_customer(q, "revops.admin", fields=["phone"])
        lookup_ms = (time.perf_counter() - t) / len(QUERIES) * 1000
        rows.append((len(records), len(res.golden), resolve_s, lookup_ms))
    print("# Scale benchmark\n")
    print("Generated by `uv run python scripts/scale_benchmark.py`; see the script docstring.\n")
    print("| Records | Entities | Resolve (s) | Lookup, mean of 4 queries (ms) |")
    print("|---|---|---|---|")
    for n, e, r, q in rows:
        print(f"| {n:,} | {e:,} | {r:.1f} | {q:.0f} |")


if __name__ == "__main__":
    main()
