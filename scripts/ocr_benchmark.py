"""OCR benchmark: render every synthetic contract as a scanned PDF, read it back, compare.

    uv run python scripts/ocr_benchmark.py [--noise 0.02] [--out docs/reports/ocr_report.md]

Reports character error rate (Latin and Arabic lines separately) and whether the contract fields
read from the scan equal the ones read from the original text. Needs tesseract (fra+ara+eng).
"""

from __future__ import annotations

import argparse
import tempfile
import time
from pathlib import Path

from canon.ingest.contracts import parse_contract
from canon.ingest.documents import extract_text, ocr_available
from canon.ingest.testdocs import cer, find_font, scanned_pdf

ROOT = Path(__file__).resolve().parents[1]
FIELDS = ("contract_number", "contract_value", "contract_start", "renewal_date", "signatory")


def _is_arabic(line: str) -> bool:
    return any("؀" <= c <= "ۿ" for c in line)


def _fields(text: str) -> dict:
    rec = parse_contract(text, "c", "x")["record"]
    out = {f.field: f.value for f in rec.facts if f.field in FIELDS}
    out["name"] = rec.name
    out["arabic_name"] = rec.alt_names[0] if rec.alt_names else None
    out["tax_id"] = rec.tax_id
    out["phone"] = rec.phone
    return out


def run(noise: float) -> dict:
    font = find_font()
    files = sorted((ROOT / "data" / "synthetic" / "contracts").glob("*.txt"))
    latin_ref = latin_hyp = arabic_ref = arabic_hyp = ""
    per_field: dict[str, list[bool]] = {}
    wrong: dict[str, list[bool]] = {}
    flagged = 0
    confs, seconds = [], 0.0
    with tempfile.TemporaryDirectory() as tmp:
        for path in files:
            src = path.read_text(encoding="utf-8")
            lines = src.split("\n")
            pages = ["\n".join(lines[:14]), "\n".join(lines[14:])]
            pdf = Path(tmp) / f"{path.stem}.pdf"
            scanned_pdf(pages, pdf, font, noise=noise)
            t = time.perf_counter()
            doc = extract_text(pdf)
            seconds += time.perf_counter() - t
            confs.append(doc.ocr_confidence or 0)
            flagged += any(r == "low_ocr_confidence" for r, _ in doc.issues)
            got = [ln for ln in doc.text.replace("\f", "\n").split("\n") if ln.strip()]
            latin_ref += " ".join(ln for ln in lines if ln.strip() and not _is_arabic(ln)) + " "
            latin_hyp += " ".join(ln for ln in got if not _is_arabic(ln)) + " "
            arabic_ref += " ".join(ln for ln in lines if _is_arabic(ln)) + " "
            arabic_hyp += " ".join(ln for ln in got if _is_arabic(ln)) + " "
            want, have = _fields(src), _fields(doc.text)
            for k, v in want.items():
                if v is not None:
                    per_field.setdefault(k, []).append(have.get(k) == v)
                    wrong.setdefault(k, []).append(have.get(k) not in (None, v))
    return {
        "docs": len(files),
        "noise": noise,
        "cer_latin": cer(latin_ref, latin_hyp),
        "cer_arabic": cer(arabic_ref, arabic_hyp),
        "confidence": sum(confs) / len(confs),
        "seconds_per_doc": seconds / len(files),
        "fields": {k: sum(v) / len(v) for k, v in per_field.items()},
        "wrong": {k: sum(v) / len(v) for k, v in wrong.items()},
        "flagged": flagged / len(files),
    }


def render(results: list[dict]) -> str:
    out = [
        "# OCR benchmark (synthetic contracts rendered as scans)",
        "",
        "Generated by `uv run python scripts/ocr_benchmark.py`. Each of the synthetic contracts is "
        "rendered as a 2-page image-only PDF (DejaVu Sans, about 200 dpi; `noise` = share of "
        "pixels "
        "flipped at random), read back with tesseract (fra+ara+eng), and parsed. A field counts as "
        "correct when the value read from the scan equals the value read from the original text; "
        "*wrong* means a different value was read (the rest were refused or not found).",
        "",
        "These are clean renders of a known font. Real scans (skew, stamps, signatures, fax "
        "artefacts, handwriting) will be worse, so measure on the client's files.",
        "",
        "| | " + " | ".join(f"noise {r['noise']:.0%}" for r in results) + " |",
        "|---|" + "---|" * len(results),
        "| documents | " + " | ".join(str(r["docs"]) for r in results) + " |",
        "| CER, Latin lines | " + " | ".join(f"{r['cer_latin']:.3f}" for r in results) + " |",
        "| CER, Arabic line | " + " | ".join(f"{r['cer_arabic']:.3f}" for r in results) + " |",
        "| mean word confidence | " + " | ".join(f"{r['confidence']:.1f}" for r in results) + " |",
        "| documents flagged `low_ocr_confidence` | "
        + " | ".join(f"{r['flagged']:.2f}" for r in results)
        + " |",
        "| seconds per document | "
        + " | ".join(f"{r['seconds_per_doc']:.2f}" for r in results)
        + " |",
    ]
    for field in results[0]["fields"]:
        out.append(
            f"| `{field}`: correct / wrong | "
            + " | ".join(
                f"{r['fields'].get(field, 0):.2f} / {r['wrong'].get(field, 0):.2f}" for r in results
            )
            + " |"
        )
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--noise", type=float, nargs="*", default=[0.0, 0.02])
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    if not ocr_available() or not find_font():
        raise SystemExit("needs tesseract (fra+ara+eng) and the DejaVu Sans font")
    report = render([run(n) for n in args.noise])
    print(report)
    if args.out:
        args.out.write_text(report, encoding="utf-8")


if __name__ == "__main__":
    main()
