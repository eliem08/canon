"""Entity resolution on real business listings: Fodors–Zagat (restaurant guides), from the Magellan
entity-matching benchmarks as packaged in `lighteval/EntityMatching` on Hugging Face.

    uv run --with pyarrow python scripts/er_benchmark.py [--split dev|test|all] [--out <report.md>]

Each listing has a name, street address, city and phone, like a CRM account; the same restaurant
appears in both guides with different spellings ("carnegie deli" / "Carnegie Deli", "213/857 -0034"
/ "213-655-8880", "new york" / "new york city"). The dataset's `class` field is the answer key
(listings of the same restaurant share it); it is used only for scoring, and the cuisine `type` is
not given to the resolver.

Files are downloaded at a pinned revision into `$CANON_CACHE` (default `~/.cache/canon`); nothing
from the dataset is committed. Listings are split by a hash of their class into a dev half (the
resolver may be tuned on it) and a test half (reported only).
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from canon.ingest.parsing import parse_phone  # noqa: E402
from canon.models import SourceRecord  # noqa: E402
from canon.resolve.evaluate import bcubed, pairwise  # noqa: E402
from canon.resolve.normalize import normalize_name  # noqa: E402
from canon.resolve.pipeline import resolve  # noqa: E402

REPO = "lighteval/EntityMatching"
REVISION = "dbc9ec9d4de43d805215f0f7da051673bd938747"
SPLITS = ("train", "validation", "test")
_FIELD = re.compile(r"(\w+): (.*?)(?=\. \w+: |$)")


def cache_dir() -> Path:
    base = Path(os.environ.get("CANON_CACHE", Path.home() / ".cache" / "canon"))
    return base / "entity_matching" / REVISION


def fetch() -> Path:
    out = cache_dir()
    for split in SPLITS:
        path = out / f"Fodors_Zagats_{split}.parquet"
        if path.exists():
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        url = (
            f"https://huggingface.co/datasets/{REPO}/resolve/{REVISION}/Fodors_Zagats/"
            f"{split}-00000-of-00001.parquet"
        )
        print(f"downloading {url}", file=sys.stderr)
        tmp = path.with_suffix(".part")
        with urllib.request.urlopen(url, timeout=120) as r, tmp.open("wb") as fh:
            fh.write(r.read())
        tmp.rename(path)
    return out


def _clean(value: str) -> str:
    value = value.replace("\\'", "'").strip()
    return re.sub(r"\s+", " ", value.strip("`' ")).strip()


def parse_listing(text: str) -> dict:
    return {k: _clean(v) for k, v in _FIELD.findall(text.strip().rstrip("."))}


def split_of(cls: str) -> str:
    return "dev" if int(hashlib.sha1(cls.encode()).hexdigest(), 16) % 2 == 0 else "test"


def load(directory: Path) -> list[dict]:
    import pyarrow.parquet as pq

    seen: dict[str, dict] = {}
    for split in SPLITS:
        for row in pq.read_table(directory / f"Fodors_Zagats_{split}.parquet").to_pylist():
            for side, text in (("a", row["productA"]), ("b", row["productB"])):
                listing = parse_listing(text)
                rid = f"{side}:{hashlib.sha1(text.encode()).hexdigest()[:10]}"
                seen.setdefault(rid, {**listing, "record_id": rid, "guide": side})
    return list(seen.values())


def to_record(item: dict) -> SourceRecord:
    phone = parse_phone(item.get("phone"), "1")  # US listings
    return SourceRecord(
        record_id=item["record_id"],
        source="crm",
        locator=f"fodors_zagat/{item['guide']}",
        name=item.get("name"),
        address=item.get("addr"),
        city=item.get("city"),
        phone=phone.value,
    )


def exact_name(items: list[dict]) -> list[list[str]]:
    groups: dict[str, list[str]] = {}
    for it in items:
        groups.setdefault(normalize_name(it.get("name")), []).append(it["record_id"])
    return list(groups.values())


def run(items: list[dict]) -> dict:
    truth = {it["record_id"]: it["class"] for it in items}
    res = resolve([to_record(it) for it in items])
    pairs = sum(n * (n - 1) // 2 for n in _sizes(truth))
    return {
        "records": len(items),
        "true_pairs": pairs,
        "canon": pairwise(res.clusters, truth),
        "canon_bcubed": bcubed(res.clusters, truth),
        "exact_name": pairwise(exact_name(items), truth),
        "review": len(res.review),
    }


def _sizes(truth: dict[str, str]) -> list[int]:
    counts: dict[str, int] = {}
    for c in truth.values():
        counts[c] = counts.get(c, 0) + 1
    return list(counts.values())


def render(results: dict[str, dict]) -> str:
    lines = [
        "# Entity resolution on real business listings (Fodors–Zagat)",
        "",
        f"Generated by `scripts/er_benchmark.py` from `{REPO}` at `{REVISION[:7]}` (Magellan "
        "Fodors–Zagat: restaurant listings from two guides, same restaurant spelled differently). "
        "Name, address, city and phone go to the resolver with its default settings; the cuisine "
        "type and the answer key do not. Aggregate numbers only; no listing is in the repo.",
        "",
    ]
    for split, r in results.items():
        c, b, e = r["canon"], r["canon_bcubed"], r["exact_name"]
        lines += [
            f"## {split} ({r['records']} listings, {r['true_pairs']} true matches)",
            "",
            "| method | precision | recall | F1 |",
            "|---|---|---|---|",
            f"| exact normalized name | {e.precision:.3f} | {e.recall:.3f} | {e.f1:.3f} |",
            f"| Canon (pairwise) | {c.precision:.3f} | {c.recall:.3f} | {c.f1:.3f} |",
            f"| Canon (B-cubed) | {b.precision:.3f} | {b.recall:.3f} | {b.f1:.3f} |",
            "",
            f"Review queue: {r['review']} pair decisions for a person to confirm.",
            "",
        ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", choices=["dev", "test", "all"], default="dev")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    items = load(fetch())
    splits = ["dev", "test"] if args.split == "all" else [args.split]
    results = {s: run([i for i in items if split_of(i["class"]) == s]) for s in splits}
    report = render(results)
    if args.out:
        Path(args.out).write_text(report + "\n", encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
