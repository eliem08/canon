"""Arabic <-> Latin name matching on real names: 23k Arabic names with their English
transliterations (`freococo/arabic_names_with_myanmar_and_english_transliteration`, CC0).

    uv run python scripts/arabic_names_benchmark.py [--split dev|test|all] [--out <md>]

Canon matches a customer named in Arabic script to the same name written in Latin script (a CRM
in French, a contract in Arabic) through its transliteration skeletons. For every name, the Arabic
and English forms are a true pair; the Arabic form against a different, random English name is a
false pair. Reported per similarity threshold: the share of true pairs that reach it (recall) and
of false pairs that reach it (false matches). The resolver never merges on a name alone; this
measures the name channel only. Names are split by a hash of their id into dev and test.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from canon.models import SourceRecord  # noqa: E402
from canon.resolve.features import features  # noqa: E402
from canon.resolve.scoring import name_similarity  # noqa: E402

REPO = "freococo/arabic_names_with_myanmar_and_english_transliteration"
REVISION = "9f9e9a33ad0e0c77ed439bb8e6654a6f3ab062c0"
FILE = "arabic_names_with_myanmar_n_english_transliteration.jsonl"
THRESHOLDS = (0.7, 0.8, 0.85, 0.9)


def fetch() -> Path:
    base = Path(os.environ.get("CANON_CACHE", Path.home() / ".cache" / "canon"))
    path = base / "arabic_names" / REVISION / FILE
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        url = f"https://huggingface.co/datasets/{REPO}/resolve/{REVISION}/{FILE}"
        print(f"downloading {url}", file=sys.stderr)
        tmp = path.with_suffix(".part")
        with urllib.request.urlopen(url, timeout=120) as r, tmp.open("wb") as fh:
            fh.write(r.read())
        tmp.rename(path)
    return path


def split_of(name_id) -> str:
    return "dev" if int(hashlib.sha1(str(name_id).encode()).hexdigest(), 16) % 2 == 0 else "test"


def load() -> list[dict]:
    rows = [json.loads(line) for line in fetch().read_text(encoding="utf-8").splitlines() if line]
    return [r for r in rows if r.get("name_ar") and r.get("name_en")]


def _f(name: str, rid: str):
    return features(SourceRecord(record_id=rid, source="crm", locator="x", name=name))


def run(rows: list[dict], sample: int, seed: int = 7) -> dict:
    rng = random.Random(seed)
    rows = rng.sample(rows, min(sample, len(rows)))
    true_sims, false_sims = [], []
    for i, row in enumerate(rows):
        ar = _f(row["name_ar"], "ar")
        true_sims.append(name_similarity(ar, _f(row["name_en"], "en")))
        other = rows[(i + 1 + rng.randrange(len(rows) - 1)) % len(rows)]
        false_sims.append(name_similarity(ar, _f(other["name_en"], "x")))
    out = {"pairs": len(rows)}
    for t in THRESHOLDS:
        out[t] = (
            sum(s >= t for s in true_sims) / len(true_sims),
            sum(s >= t for s in false_sims) / len(false_sims),
        )
    single = [s for row, s in zip(rows, true_sims, strict=True) if " " not in row["name_en"]]
    out["single_word_recall_85"] = sum(s >= 0.85 for s in single) / max(len(single), 1)
    return out


def render(results: dict) -> str:
    lines = [
        "# Arabic <-> Latin name matching on real names",
        "",
        f"Generated by `scripts/arabic_names_benchmark.py` from `{REPO}` at `{REVISION[:7]}` "
        "(CC0). "
        "Each Arabic name against its own English transliteration (true pair) and against a random "
        "other English name (false pair), compared with Canon's name similarity.",
        "",
    ]
    for split, r in results.items():
        lines += [
            f"## {split} ({r['pairs']} names)",
            "",
            "| threshold | true pairs reaching it (recall) | false pairs reaching it |",
            "|---|---|---|",
        ]
        for t in THRESHOLDS:
            rec, fp = r[t]
            lines.append(f"| {t} | {rec:.1%} | {fp:.2%} |")
        lines += ["", f"Single-word names at 0.85: {r['single_word_recall_85']:.1%}.", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", choices=["dev", "test", "all"], default="dev")
    ap.add_argument("--sample", type=int, default=3000)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    rows = load()
    splits = ["dev", "test"] if args.split == "all" else [args.split]
    results = {
        s: run([r for r in rows if split_of(r["name_id"]) == s], args.sample) for s in splits
    }
    report = render(results)
    if args.out:
        Path(args.out).write_text(report + "\n", encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
