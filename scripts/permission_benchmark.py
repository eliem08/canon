"""Permission leaks at scale: how often each agent's context contains a record the caller may not
read, for every caller in the identities file, over many regenerated datasets.

    uv run python scripts/permission_benchmark.py [--seeds 10] [--out <report.md>]

A leak is decided by the retrieved context, not by the model's answer: if a restricted record is
in what the model reads, the model can repeat it. So this needs no model; the stub model drives
the agents and the count is the same for any model. Canon applies ACLs before scoring, so its
count should be 0 for everyone; the RAG baselines read the raw export.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from canon.evals import StubModel  # noqa: E402
from canon.evals.harness import run_eval  # noqa: E402
from canon.synth import generate  # noqa: E402

AGENTS = {"baseline": "Keyword RAG", "hybrid": "Strong RAG", "canon": "Canon"}


def run(seeds: int) -> tuple[dict, dict, int]:
    leaks: dict = defaultdict(lambda: defaultdict(int))  # role -> agent -> leaky answers
    answers: dict = defaultdict(int)  # role -> answers
    callers_seen = 0
    for seed in range(1, seeds + 1):
        with tempfile.TemporaryDirectory() as d:
            generate(Path(d), seed=seed)
            callers = json.loads((Path(d) / "identities.json").read_text())["callers"]
            for caller, entry in callers.items():
                groups = set(entry.get("groups", []))
                if {"sales", "legal", "exec"} <= groups:
                    continue  # sees everything: nothing to leak
                role = "+".join(sorted(groups)) or "no access"
                result = run_eval(Path(d), StubModel(), caller=caller)
                callers_seen += 1
                answers[role] += len(result.results)
                for agent in AGENTS:
                    leaks[role][agent] += result.leaky(agent)
    return leaks, answers, callers_seen


def render(leaks: dict, answers: dict, seeds: int, callers: int) -> str:
    lines = [
        "# Permission leaks at scale",
        "",
        f"Generated by `scripts/permission_benchmark.py --seeds {seeds}`: {seeds} regenerated "
        f"synthetic datasets, {callers} caller runs (every caller who is not an administrator), 40 "
        "questions each. An answer leaks when its context contains a record the caller may not "
        "read. This is decided by retrieval, so it holds for any model.",
        "",
        "| caller role | answers | " + " | ".join(AGENTS.values()) + " |",
        "|---|---|" + "---|" * len(AGENTS),
    ]
    total = sum(answers.values())
    for role in sorted(answers):
        n = answers[role]
        cells = [f"{leaks[role][a]} ({leaks[role][a] / n:.0%})" for a in AGENTS]
        lines.append(f"| {role} | {n} | " + " | ".join(cells) + " |")
    cells = [
        f"**{sum(leaks[r][a] for r in leaks)} ({sum(leaks[r][a] for r in leaks) / total:.0%})**"
        for a in AGENTS
    ]
    lines.append(f"| **all** | {total} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=10)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    leaks, answers, callers = run(args.seeds)
    report = render(leaks, answers, args.seeds, callers)
    if args.out:
        Path(args.out).write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
